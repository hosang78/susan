def strip_cite(t):
    for c in CITE: t=c.sub('',t)
    return t
def sentences(t):
    t=strip_cite(t.replace('\r',''))
    parts=re.split(r'(?<=[.!?다])\s+(?=[가-힣A-Z0-9(])|\n+',t)
    out=[]
    for p in parts:
        p=(p or '').strip()
        if not p or not re.search('[가-힣]',p): continue
        m=re.match(r'^([^가-힣]{10,}?)(?=[가-힣])',p)
        if m and (';' in m.group(1) or 'Vert' in m.group(1) or 'GR.' in m.group(1)): p=p[m.end():].strip()
        if p: out.append(p)
    return out
def is_meristic(s):
    if FORMULA.search(s): return True
    k=sum(1 for w in MERI if w in s)
    d=len(re.findall(r'\d',s))
    return (k>=1 and d>=4) or k>=3
def norm(s): return re.sub(r'[\s.,;:()]','',s)
def clean_sents(texts,drop_meristic=True,seen=None):
    seen=[] if seen is None else seen;out=[];dropped=0
    for t in texts:
        for s in sentences(t):
            n=norm(s)
            if len(n)<3: continue
            if any(n in x or x in n for x in seen if min(len(n),len(x))>=12): 
                # keep the longer one if new is longer superset
                continue
            if drop_meristic and is_meristic(s): dropped+=1; continue
            seen.append(n); out.append(s)
    return out,dropped
def gloss(text):
    used=set()
    def f(m):
        w=m.group(0)
        if w in used: return w
        used.add(w)
        nxt=text[m.end():m.end()+1]
        if nxt=='(': return w
        return f'{w}({GLOSS[w]})'
    return TERM_RE.sub(f,text)
def limit(text,n):
    if len(text)<=n: return text
    cut=text[:n]; i=max(cut.rfind('다. '),cut.rfind('다.'))
    return (cut[:i+2] if i>n*0.5 else cut).strip()+' …'
